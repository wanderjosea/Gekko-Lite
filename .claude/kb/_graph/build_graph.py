#!/usr/bin/env python3
"""
build_graph.py — Turn the Gekko-Lite knowledge base into an Obsidian-style graph.

Parses the curated `.claude/kb/` notes (frontmatter + wikilinks + tags) and
emits a single self-contained HTML file with a dependency-free, force-directed
"neural network" view. No CDN / no outbound network required (works offline
via file://).

Usage:
    python3 .claude/kb/_graph/build_graph.py
    # -> writes .claude/kb/_graph/kb-graph.html  (open in a browser)

Edges:
    - wikilink  : an explicit `[[slug]]` reference   (strongest, solid)
    - tag       : two notes share >= MIN_SHARED_TAGS  (weight = shared count)
Nodes are colored by category and sized by degree (link count).
"""
from __future__ import annotations
import json
import re
import sys
from pathlib import Path

# ── config ────────────────────────────────────────────────────────────────
KB = Path(__file__).resolve().parent.parent          # .claude/kb
OUT = Path(__file__).resolve().parent / "kb-graph.html"
README = KB / "README.md"                             # index, regenerated in place
# Regenerated block lives between these markers; everything else in README is
# hand-written and preserved verbatim.
IDX_START = "<!-- AUTO-INDEX:START — generated by _graph/build_graph.py, do not edit by hand -->"
IDX_END = "<!-- AUTO-INDEX:END -->"
CAT_ORDER = ["techniques", "tools", "payloads", "platforms"]  # section order
MIN_SHARED_TAGS = 1          # tag-edge threshold (1 = dense/neural, 2 = clusters, 3 = sparse)

# Content notes only: skip meta files and the vendored PoC tree.
CONTENT_GLOBS = ["techniques/*.md", "tools/*.md", "platforms/*.md",
                 "payloads/reverse-shells.md",
                 "payloads/bad-epoll-cve-2026-46242/README.md"]
CATEGORY_COLOR = {
    "techniques": "#ff6b6b", "tools": "#4dd4c0", "platforms": "#ffd166",
    "payloads": "#a78bfa", "unknown": "#8899aa",
}

WIKILINK = re.compile(r"\[\[([^\]|#]+)")             # [[slug]] / [[slug|alias]]

# ── frontmatter (tiny YAML subset, no dependency) ──────────────────────────
def parse_front(text: str) -> tuple[dict, str]:
    if not text.startswith("---"):
        return {}, text
    end = text.find("\n---", 3)
    if end == -1:
        return {}, text
    raw, body = text[3:end], text[end + 4:]
    fm: dict = {}
    for line in raw.splitlines():
        if ":" not in line or line.strip().startswith("#"):
            continue
        key, _, val = line.partition(":")
        key, val = key.strip(), val.split("#")[0].strip()
        if val.startswith("[") and val.endswith("]"):
            fm[key] = [t.strip() for t in val[1:-1].split(",") if t.strip()]
        else:
            fm[key] = val.strip('"').strip("'")
    return fm, body


def collect() -> list[dict]:
    notes = []
    for pat in CONTENT_GLOBS:
        for path in sorted(KB.glob(pat)):
            fm, body = parse_front(path.read_text(encoding="utf-8", errors="ignore"))
            # READMEs have no frontmatter → name the node after its folder
            stem = path.parent.name if path.stem == "README" else path.stem
            slug = fm.get("slug") or stem
            cat = fm.get("category")
            if not cat:
                cat = path.relative_to(KB).parts[0]
            tags = fm.get("tags") if isinstance(fm.get("tags"), list) else []
            # sorted → deterministic edge order (str-set iteration is hash-randomized)
            links = sorted({m.group(1).strip() for m in WIKILINK.finditer(body)})
            notes.append({
                "slug": slug,
                # README-backed notes name a directory entry → show a trailing slash
                "index_name": (slug + "/") if path.stem == "README" else slug,
                "title": fm.get("title") or slug,
                "category": cat if cat in CATEGORY_COLOR else "unknown",
                "summary": fm.get("summary", ""),
                "tags": tags,
                "wikilinks": links,
                "updated": fm.get("updated", ""),
                "chars": len(body),
            })
    return notes


def build(notes: list[dict]) -> dict:
    by_slug = {n["slug"]: n for n in notes}
    edges: dict[tuple[str, str], dict] = {}

    def add(a: str, b: str, kind: str, w: float):
        if a == b or a not in by_slug or b not in by_slug:
            return
        key = tuple(sorted((a, b)))
        cur = edges.get(key)
        # wikilink beats tag; otherwise keep the heavier weight
        if cur is None or (kind == "wikilink" and cur["kind"] != "wikilink") \
                or w > cur["weight"]:
            edges[key] = {"source": key[0], "target": key[1],
                          "kind": "wikilink" if (cur and cur["kind"] == "wikilink")
                          or kind == "wikilink" else kind,
                          "weight": max(w, cur["weight"] if cur else 0)}

    # explicit wikilinks
    for n in notes:
        for tgt in n["wikilinks"]:
            add(n["slug"], tgt, "wikilink", 3.0)
    # shared-tag edges
    for i, a in enumerate(notes):
        ta = set(a["tags"])
        for b in notes[i + 1:]:
            shared = ta & set(b["tags"])
            if len(shared) >= MIN_SHARED_TAGS:
                add(a["slug"], b["slug"], "tag", float(len(shared)))

    deg: dict[str, int] = {n["slug"]: 0 for n in notes}
    for e in edges.values():
        deg[e["source"]] += 1
        deg[e["target"]] += 1
    for n in notes:
        n["degree"] = deg[n["slug"]]
        n["tags"] = list(n["tags"])
        del n["wikilinks"]

    ordered = sorted(edges.values(), key=lambda e: (e["source"], e["target"]))
    return {"nodes": notes, "edges": ordered, "colors": CATEGORY_COLOR}


def render(graph: dict) -> str:
    data = json.dumps(graph, ensure_ascii=False)
    n_nodes = len(graph["nodes"])
    n_edges = len(graph["edges"])
    wl = sum(1 for e in graph["edges"] if e["kind"] == "wikilink")
    return HTML.replace("__DATA__", data).replace("__NODES__", str(n_nodes)) \
               .replace("__EDGES__", str(n_edges)).replace("__WL__", str(wl))


