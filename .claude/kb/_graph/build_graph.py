def write_readme(notes: list[dict]) -> int:
    """Regenerate the index tables between the AUTO-INDEX markers in README.md.
    Source of truth is each note's frontmatter — no manual list to drift."""
    if not README.exists():
        print("README.md not found — skipping index regen", file=sys.stderr)
        return 0
    text = README.read_text(encoding="utf-8")
    i, j = text.find(IDX_START), text.find(IDX_END)
    if i == -1 or j == -1 or j < i:
        print("AUTO-INDEX markers missing in README.md — skipping index regen",
              file=sys.stderr)
        return 0

    by_cat: dict[str, list[dict]] = {}
    for n in notes:
        by_cat.setdefault(n["category"], []).append(n)

    lines = [IDX_START, ""]
    for cat in CAT_ORDER:
        rows = sorted(by_cat.get(cat, []), key=lambda n: n["index_name"])
        if not rows:
            continue
        lines += [f"## {cat}/", "| Entry | Purpose | Updated |", "|---|---|---|"]
        for n in rows:
            purpose = (n["summary"] or "").replace("|", "\\|")
            lines.append(f"| {n['index_name']} | {purpose} | {n['updated'] or ''} |")
        lines.append("")
    block = "\n".join(lines).rstrip() + "\n"

    new = text[:i] + block + text[j:]
    if new != text:
        README.write_text(new, encoding="utf-8")
        print(f"KB index: {sum(len(v) for v in by_cat.values())} entries across "
              f"{sum(1 for c in CAT_ORDER if by_cat.get(c))} categories → README.md")
    else:
        print("KB index: README.md already up to date")
    return 0


def main() -> int:
    notes = collect()
    if not notes:
        print("No KB notes found under", KB, file=sys.stderr)
        return 1
    write_readme(notes)
    graph = build(notes)
    OUT.write_text(render(graph), encoding="utf-8")
    e = graph["edges"]
    wl = sum(1 for x in e if x["kind"] == "wikilink")
    print(f"KB graph: {len(graph['nodes'])} nodes, {len(e)} edges "
          f"({wl} wikilinks, {len(e)-wl} tag-edges)")
    print("Wrote", OUT.relative_to(KB.parent.parent))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
